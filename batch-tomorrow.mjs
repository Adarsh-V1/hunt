const results = [];
let globalFailure = false;

for (const company of companies) {
  if (globalFailure) {
    results.push({ company: company.name, email: "", result: "SKIPPED (global failure)" });
    continue;
  }

  let tracker = null;
  try { tracker = await findTrackerCompany({ companyName: company.name }); } catch {}

  for (const email of company.emails) {
    const body = bodyTemplate(company.name);
    process.stdout.write(`--- SENDING: ${company.name} <${email}> --- `);

    try {
      const sendResult = await sendApplicationEmail({
        recipientEmail: email,
        subject: "Application for Full-Stack Developer Role",
        body,
        companyName: company.name,
        roleTarget: "Full-Stack Developer",
        resumeFile,
      });

      if (tracker) {
        try { await recordApplicationEmailSent({ companyId: tracker.id, companyName: tracker.companyName, recipientEmail: sendResult.recipientEmail, resumeFileName: sendResult.resumeFileName, message: "Email sent successfully." }); } catch {}
      }

      console.log("SENT  " + (sendResult.messageId || ""));
      results.push({ company: company.name, email, result: "SENT", messageId: sendResult.messageId || "" });
    } catch (error) {
      const m = error?.message || "Unknown error";
      const isGlobal = m.toLowerCase().includes("login") || m.toLowerCase().includes("auth") || error?.code === "EAUTH" || m.toLowerCase().includes("quota") || m.toLowerCase().includes("daily");
      if (isGlobal) globalFailure = true;

      if (tracker) {
        try { await recordApplicationEmailFailure({ companyId: tracker.id, companyName: tracker.companyName, recipientEmail: email, message: m }); } catch {}
      }

      console.log("FAIL: " + m.slice(0, 80));
      results.push({ company: company.name, email, result: `FAIL: ${m}`, messageId: "" });

      if (isGlobal) {
        console.error("\nGLOBAL SMTP FAILURE - stopped");
        break;
      }
    }
  }
}

